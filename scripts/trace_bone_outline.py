#!/usr/bin/env python3
"""Trace the painted bone PNGs into the T09 model outline.

    python3 -I scripts/trace_bone_outline.py

The painting defines the bone shape: each PNG (cropped to its silhouette) is
scaled uniformly so its length equals the model length, and its top / bottom
silhouette edges are sampled every 1 mm. The y origin is the shaft centre at
the fracture line (the fragment's rotation pivot). Writes
src/config/boneOutlines.generated.ts, which the engine and the drawings use
instead of the old symmetric width profile.
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "src/assets/illust/surgery"
OUT = ROOT / "src/config/boneOutlines.generated.ts"

# case: (bone painting, model length mm, fracture x mm, companion painting or None)
CASES = {
    "C07": ("C07-bone.png", 80, 56, "C07-ulna.png"),
    "C08": ("C08-bone.png", 100, 50, None),
}
ALPHA = 128  # silhouette threshold


def columns(img: Image.Image) -> list[tuple[int, int] | None]:
    a = img.getchannel("A")
    w, h = img.size
    px = a.load()
    cols: list[tuple[int, int] | None] = []
    for x in range(w):
        ys = [y for y in range(h) if px[x, y] > ALPHA]
        cols.append((ys[0], ys[-1] + 1) if ys else None)
    return cols


def trace(file: str, length: float):
    img = Image.open(ART / file).convert("RGBA")
    w, h = img.size
    k = length / w  # mm per px, same on both axes (no stretching)
    cols = columns(img)

    def col_at(xmm: float) -> tuple[int, int]:
        i = min(w - 1, max(0, round(xmm / k)))
        for d in range(w):  # nearest non-empty column (the very tips can be empty)
            for j in (i - d, i + d):
                if 0 <= j < w and cols[j]:
                    return cols[j]  # type: ignore[return-value]
        raise ValueError(f"{file}: empty silhouette")

    edges = []
    for xmm in range(0, int(length) + 1):
        t, b = col_at(float(xmm))
        edges.append([xmm, t * k, b * k])
    return edges, h * k


def main() -> None:
    data = {}
    for case, (file, length, fx, companion) in CASES.items():
        edges, height = trace(file, length)
        t, b = next((e[1], e[2]) for e in edges if e[0] == fx)
        c = (t + b) / 2  # shaft centre at the fracture = y origin
        entry = {
            "edges": [[x, round(tp - c, 2), round(bt - c, 2)] for x, tp, bt in edges],
            "paint": {"y": round(-c, 3), "height": round(height, 3)},
        }
        if companion:
            cedges, cheight = trace(companion, length)
            # the companion sits just below the main bone's lowest point along the shaft
            shaft = [e for e in entry["edges"] if 0.15 * length <= e[0] <= 0.85 * length]
            below = max(e[2] for e in shaft) + 0.6
            ctop = min(e[1] for e in cedges if 0.15 * length <= e[0] <= 0.85 * length)
            dy = below - ctop
            entry["companion"] = {
                "edges": [[x, round(tp + dy, 2), round(bt + dy, 2)] for x, tp, bt in cedges],
                "paint": {"y": round(dy, 3), "height": round(cheight, 3)},
            }
        data[case] = entry
        widths = [round(e[2] - e[1], 2) for e in entry["edges"] if e[0] in (int(length * 0.25), int(length * 0.5), int(length * 0.75))]
        print(f"{case}: {len(entry['edges'])} samples, shaft widths at 25/50/75% = {widths} mm")

    body = json.dumps(data, separators=(",", ":"))
    OUT.write_text(
        "// GENERATED by scripts/trace_bone_outline.py from the painted bone PNGs. Do not edit.\n"
        "// edges: [x, top, bottom] in model mm every 1 mm; paint: where the PNG is drawn (x 0..length).\n"
        "import type { BoneOutline } from './boneOutline';\n\n"
        f"export const BONE_OUTLINES: Record<string, BoneOutline> = {body};\n"
    )
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
